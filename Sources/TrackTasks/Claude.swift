        Если подходит несколько — выбери самый вероятный. Если неясно — выбери самый вероятный и напиши в описании задачи «Проект определён неуверенно».
        Если в about.md выбранного проекта есть раздел «## Definition of Done», добавь его пункты в «## Критерии готовности» новой задачи (без дублей).
        Перед созданием можно заглянуть в about.md кандидатов. В конце одной строкой: «Проект → файл».
        """
    }
