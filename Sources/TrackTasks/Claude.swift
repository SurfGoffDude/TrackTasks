    static func split(_ t: TaskItem) -> String {
        "Разбей задачу tasks/\(t.fileName) («\(t.title)») на 2–6 конкретных подзадач: создай отдельные файлы задач в tasks/ по формату (свой size, чек-лист, «Критерии готовности»; в описании — «Подзадача для tasks/\(t.fileName)»). Если подзадачи должны идти по порядку — свяжи их через depends:. Исходную задачу не удаляй: добавь все подзадачи в её depends:, а пункты её чек-листа, вынесенные в подзадачи, убери. В конце — список созданных файлов."
    }

    static func refine(_ t: TaskItem) -> String {
        "Уточни задачу tasks/\(t.fileName) («\(t.title)»): изучи релевантный код и приведи её к формату трекера — в описание контекст и затрагиваемые файлы (пути вида src/x.ts), план — чек-листом шагов, проверяемые условия — в «## Критерии готовности», оцени size (s/m/l), найденные зависимости от других задач в tasks/ — в depends:. Что уже было в задаче (отметки [x], заметки, статус) не теряй. Статус не меняй."
    }

    static func runTask(_ t: TaskItem) -> String {
        "Выполни задачу из файла tasks/\(t.fileName) («\(t.title)»). Сначала прочитай её, about.md и spectrack.md (если есть). Если есть раздел «Критерии готовности» — задача готова, только когда все они выполнены. Отмечай выполненные пункты чек-листов ([x]). \(evidence) Когда закончишь — поставь в файле задачи status: done и completed: сегодняшнюю дату, и допиши в тело раздел «Итог» с кратким описанием сделанного. Важные решения по ходу можно дописать строкой «- дд.мм чч:мм — …» в раздел «## Заметки»."
    }

    static func quickAdd(_ text: String) -> String {
        """
        Пользователь хочет добавить задачу: «\(text)»
