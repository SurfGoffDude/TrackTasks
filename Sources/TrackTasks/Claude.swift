    @MainActor static func review(task: Job) -> String {
        let diff = task.worktree != nil && !task.baseCommit.isEmpty
            ? "`git diff \(task.baseCommit.prefix(12))..HEAD` (коммиты этой задачи в текущей ветке)"
            : "`git diff HEAD` и `git status` (незакоммиченные изменения; часть может быть не от этой задачи)"
        return """
        Сделай код-ревью изменений по задаче «\(task.title)»\(task.taskPath.map { " (файл задачи: \($0))" } ?? "").
        Изменения смотри через \(diff).
        Проверь по порядку: ошибки логики и крайние случаи, безопасность, слабые или отсутствующие тесты, отклонения от задачи (если в файле задачи есть «Критерии готовности» — пройди по каждому: строка «\(Evidence.label)» под ним — слова исполнителя, сверь её с diff и кодом; отмеченные пункты без неё назови) и лишние изменения. Стиль и вкусовые правки не указывай. Файлы не меняй.
        Ответ: первая строка строго «ВЕРДИКТ: ОК» (можно сливать) или «ВЕРДИКТ: ПРАВКИ». Дальше — замечания с пометкой «критично» (ломает работу или критерий) или «желательно», каждое с файлом, строкой и сценарием, при котором это проявится. Кратко.
        """
    }

    static func resolveMerge(task: String, branch: String, main: String) -> String {
        """
        Ветка \(branch) (задача «\(task)») не сливается в основную ветку проекта из-за конфликта. Ты в её worktree.
        1. Влей в эту ветку текущее состояние основной папки: `git merge --no-edit $(git -C '\(main)' rev-parse HEAD)`.
        2. Разреши все конфликты: сохрани смысл обеих сторон — изменения задачи и то, что уже есть в основной ветке. Ничего не выбрасывай молча; если стороны несовместимы — оставь вариант основной ветки и перенеси идею задачи поверх него.
        3. Убедись, что маркеров <<<<<<< / >>>>>>> не осталось (`git diff --check`), проект собирается и тесты проходят (если есть).
        4. `git add` разрешённые файлы и закоммить слияние. Файлы в основной папке \(main) не трогай.
        В конце — какие файлы конфликтовали и как разрешено, по строке на файл.
        """
    }

