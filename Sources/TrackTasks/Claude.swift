enum ClaudeModel: String, CaseIterable, Identifiable {
    case auto, fable, opus, sonnet, haiku
    var id: String { rawValue }

    static let storageKey = "claudeModel"
    static let backgroundKey = "backgroundModel"
    static let planningKey = "planningModel"

    /// Model for chat and background task execution.
    static var current: ClaudeModel {
        ClaudeModel(rawValue: UserDefaults.standard.string(forKey: storageKey) ?? "") ?? .auto
    }

    /// Model for light background jobs (about.md, quick add).
    static var background: ClaudeModel {
        ClaudeModel(rawValue: UserDefaults.standard.string(forKey: backgroundKey) ?? "") ?? .sonnet
    }

    /// Model for the chat's planning actions (suggest / refine / split / restructure).
    static var planning: ClaudeModel {
        ClaudeModel(rawValue: UserDefaults.standard.string(forKey: planningKey) ?? "") ?? .sonnet
    }

    /// Value for `claude --model`; empty = CLI default.
    var alias: String { self == .auto ? "" : rawValue }

    var title: String {
        switch self {
        case .auto: "По умолчанию"
        case .fable: "Fable"
        case .opus: "Opus"
        case .sonnet: "Sonnet"
        case .haiku: "Haiku"
        }
    }

    var hint: String {
        switch self {
        case .auto: "как в настройках claude"
        case .fable: "самая умная"
        case .opus: "мощная"
        case .sonnet: "баланс"
        case .haiku: "быстрая, дешёвая"
        }
    }
}

enum ClaudeLocator {
    private static let lock = NSLock()
    private static var cached: String?

    /// Without starting a shell: the path from Settings, what was found before, the usual places.
    static func known() -> String? {
        let fm = FileManager.default
        let o = (UserDefaults.standard.string(forKey: "claudePath") ?? "").trimmingCharacters(in: .whitespaces)
        if !o.isEmpty, fm.isExecutableFile(atPath: o) { return o }
        lock.lock(); defer { lock.unlock() }
        return usual()
    }

    /// Under `lock`.
    private static func usual() -> String? {
        if let c = cached { return c }
        let fm = FileManager.default
        let home = NSHomeDirectory()
        var candidates = [
            "\(home)/.local/bin/claude",
            "\(home)/.claude/local/claude",
            "/opt/homebrew/bin/claude",
            "/usr/local/bin/claude",
        ]
        let nvm = "\(home)/.nvm/versions/node"
        if let versions = try? fm.contentsOfDirectory(atPath: nvm) {
            for v in versions.sorted(by: >) { candidates.append("\(nvm)/\(v)/bin/claude") }
        }
        if let found = candidates.first(where: { fm.isExecutableFile(atPath: $0) }) {
            cached = found
            return found
        }
        return nil
    }

    static func resolve() -> String? {
        if let k = known() { return k }
        let fm = FileManager.default
        lock.lock(); defer { lock.unlock() }
        if let c = cached { return c }
        // Not in a known location: ask the user's interactive shell.
        let p = Process()
        p.executableURL = URL(fileURLWithPath: "/bin/zsh")
        p.arguments = ["-ilc", "command -v claude"]
        let out = Pipe()
        p.standardOutput = out
        p.standardError = FileHandle.nullDevice
        p.standardInput = FileHandle.nullDevice
        do { try p.run() } catch { return nil }
        let data = out.fileHandleForReading.readDataToEndOfFile()
        p.waitUntilExit()
        let text = String(data: data, encoding: .utf8) ?? ""
        let path = text.components(separatedBy: "\n").last { $0.hasPrefix("/") }?
            .trimmingCharacters(in: .whitespaces)
        if let path, fm.isExecutableFile(atPath: path) { cached = path }
        return cached
    }
}

